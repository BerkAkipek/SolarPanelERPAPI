CREATE VIEW inventory_availability AS
WITH deltas AS (
    SELECT organization_id, item_revision_id, to_location_id AS location_id, quantity
    FROM inventory_movement_lines WHERE to_location_id IS NOT NULL
    UNION ALL
    SELECT organization_id, item_revision_id, from_location_id, -quantity
    FROM inventory_movement_lines WHERE from_location_id IS NOT NULL
), stock AS (
    SELECT organization_id, item_revision_id, location_id, sum(quantity) AS on_hand_quantity
    FROM deltas GROUP BY organization_id, item_revision_id, location_id
), reserved AS (
    SELECT organization_id, item_revision_id, location_id, sum(quantity) AS reserved_quantity
    FROM stock_reservations WHERE status = 'ACTIVE'
    GROUP BY organization_id, item_revision_id, location_id
)
SELECT coalesce(s.organization_id, r.organization_id) AS organization_id,
       coalesce(s.item_revision_id, r.item_revision_id) AS item_revision_id,
       coalesce(s.location_id, r.location_id) AS location_id,
       coalesce(s.on_hand_quantity, 0) AS on_hand_quantity,
       coalesce(r.reserved_quantity, 0) AS reserved_quantity,
       coalesce(s.on_hand_quantity, 0) - coalesce(r.reserved_quantity, 0) AS available_quantity
FROM stock s FULL JOIN reserved r USING (organization_id, item_revision_id, location_id);

CREATE FUNCTION touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN NEW.updated_at := now(); RETURN NEW; END $$;

CREATE FUNCTION reject_history_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION '% is append-only; create a correcting record', TG_TABLE_NAME; END $$;

-- All stock writes serialize per organization for this small V1.
-- READ COMMITTED ensures checks after waiting see the preceding committed stock writes.
CREATE FUNCTION lock_stock() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF current_setting('transaction_isolation') <> 'read committed' THEN
        RAISE EXCEPTION 'Stock writes require READ COMMITTED isolation';
    END IF;
    PERFORM pg_advisory_xact_lock(NEW.organization_id);
    RETURN NEW;
END $$;

CREATE FUNCTION validate_stock() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE balance numeric; reserved_total numeric; demand numeric;
BEGIN
    IF TG_TABLE_NAME = 'stock_reservations' THEN
        IF TG_OP = 'UPDATE' THEN
            IF (NEW.organization_id, NEW.item_revision_id, NEW.location_id,
                NEW.sales_order_line_id, NEW.production_order_material_id, NEW.quantity)
               IS DISTINCT FROM
               (OLD.organization_id, OLD.item_revision_id, OLD.location_id,
                OLD.sales_order_line_id, OLD.production_order_material_id, OLD.quantity) THEN
                RAISE EXCEPTION 'Reservation allocation is immutable; release and create a new reservation';
            END IF;
            IF OLD.status <> 'ACTIVE' AND NEW.status <> OLD.status THEN
                RAISE EXCEPTION 'A terminal reservation cannot change status';
            END IF;
        END IF;
        IF NEW.status = 'ACTIVE' THEN
            IF NOT EXISTS (
                SELECT 1 FROM inventory_locations WHERE id = NEW.location_id
                AND is_active AND location_type IN ('WAREHOUSE', 'BIN', 'PRODUCTION')
            ) THEN RAISE EXCEPTION 'Stock location is not reservable'; END IF;
            SELECT available_quantity INTO balance FROM inventory_availability
            WHERE organization_id = NEW.organization_id AND item_revision_id = NEW.item_revision_id
              AND location_id = NEW.location_id;
            IF coalesce(balance, 0) < 0 THEN RAISE EXCEPTION 'Insufficient available stock'; END IF;
            IF NEW.sales_order_line_id IS NOT NULL THEN
                SELECT quantity INTO demand FROM sales_order_lines WHERE id = NEW.sales_order_line_id;
                SELECT sum(quantity) INTO reserved_total FROM stock_reservations
                WHERE sales_order_line_id = NEW.sales_order_line_id AND status IN ('ACTIVE', 'CONSUMED');
            ELSE
                SELECT required_quantity INTO demand FROM production_order_materials
                WHERE id = NEW.production_order_material_id;
                SELECT sum(quantity) INTO reserved_total FROM stock_reservations
                WHERE production_order_material_id = NEW.production_order_material_id AND status IN ('ACTIVE', 'CONSUMED');
            END IF;
            IF reserved_total > demand THEN RAISE EXCEPTION 'Reservation exceeds demand'; END IF;
        END IF;
    ELSIF NEW.from_location_id IS NOT NULL THEN
        SELECT available_quantity INTO balance FROM inventory_availability
        WHERE organization_id = NEW.organization_id AND item_revision_id = NEW.item_revision_id
          AND location_id = NEW.from_location_id;
        IF coalesce(balance, 0) < 0 THEN RAISE EXCEPTION 'Movement would consume unavailable stock'; END IF;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER lock_movement_stock BEFORE INSERT ON inventory_movement_lines
FOR EACH ROW EXECUTE FUNCTION lock_stock();
