CREATE FUNCTION protect_bom() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE parent_status text;
BEGIN
    IF TG_TABLE_NAME = 'bom_lines' THEN
        IF TG_OP = 'UPDATE' AND (NEW.bom_id, NEW.organization_id) IS DISTINCT FROM (OLD.bom_id, OLD.organization_id) THEN
            RAISE EXCEPTION 'BOM lines cannot move between BOMs';
        END IF;
        SELECT status INTO parent_status FROM boms
        WHERE id = CASE WHEN TG_OP = 'DELETE' THEN OLD.bom_id ELSE NEW.bom_id END FOR UPDATE;
        IF parent_status <> 'DRAFT' THEN RAISE EXCEPTION 'Only draft BOM lines can change'; END IF;
    ELSE
        IF OLD.status <> 'DRAFT' THEN
            IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'Approved BOM history cannot be deleted'; END IF;
            IF (NEW.organization_id, NEW.product_revision_id, NEW.version, NEW.output_quantity)
               IS DISTINCT FROM (OLD.organization_id, OLD.product_revision_id, OLD.version, OLD.output_quantity)
               OR NEW.status NOT IN (OLD.status, 'OBSOLETE') THEN
                RAISE EXCEPTION 'Approved BOM recipe is immutable; create a new version';
            END IF;
        END IF;
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER protect_bom_header BEFORE UPDATE OR DELETE ON boms FOR EACH ROW EXECUTE FUNCTION protect_bom();
CREATE TRIGGER protect_bom_lines BEFORE INSERT OR UPDATE OR DELETE ON bom_lines FOR EACH ROW EXECUTE FUNCTION protect_bom();

CREATE FUNCTION validate_production() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE recipe_status text; calculated numeric;
BEGIN
    IF TG_TABLE_NAME = 'production_orders' THEN
        SELECT status INTO recipe_status FROM boms WHERE id = NEW.bom_id FOR SHARE;
        IF recipe_status <> 'APPROVED' THEN RAISE EXCEPTION 'Production requires an approved exact BOM'; END IF;
    ELSE
        SELECT round(p.quantity * l.quantity / b.output_quantity, 6) INTO calculated
        FROM production_orders p JOIN boms b ON b.id = p.bom_id
        JOIN bom_lines l ON l.bom_id = b.id
        WHERE p.id = NEW.production_order_id AND l.id = NEW.bom_line_id;
        IF NEW.required_quantity IS DISTINCT FROM calculated THEN
            RAISE EXCEPTION 'Material requirement must equal production quantity * BOM line quantity / BOM output quantity';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER check_production_bom BEFORE INSERT ON production_orders FOR EACH ROW EXECUTE FUNCTION validate_production();
