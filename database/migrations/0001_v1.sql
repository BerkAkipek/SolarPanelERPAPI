CREATE TABLE organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE business_partners (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    code VARCHAR(50) NOT NULL,
    name VARCHAR(255) NOT NULL,
    tax_number VARCHAR(50),
    email VARCHAR(255),
    phone VARCHAR(50),
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (organization_id, code),
    UNIQUE (organization_id, id)
);

CREATE TABLE items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    sku VARCHAR(100) NOT NULL,
    name VARCHAR(255) NOT NULL,
    item_type VARCHAR(30) NOT NULL DEFAULT 'MATERIAL' CHECK (item_type IN ('MATERIAL', 'COMPONENT', 'PRODUCT')),
    base_uom VARCHAR(20) NOT NULL,
    tracking_type VARCHAR(20) NOT NULL DEFAULT 'NONE' CHECK (tracking_type IN ('NONE', 'LOT', 'SERIAL')),
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (organization_id, sku),
    UNIQUE (organization_id, id)
);

CREATE TABLE item_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    item_id BIGINT NOT NULL,
    revision_code VARCHAR(50) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'ACTIVE', 'OBSOLETE')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (organization_id, item_id) REFERENCES items(organization_id, id),
    UNIQUE (item_id, revision_code),
    UNIQUE (organization_id, id)
);

CREATE TABLE boms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    product_revision_id BIGINT NOT NULL,
    version INTEGER NOT NULL CHECK (version > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'APPROVED', 'OBSOLETE')),
    output_quantity NUMERIC(18,6) NOT NULL CHECK (output_quantity > 0 AND output_quantity <> 'NaN'::numeric),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (organization_id, product_revision_id) REFERENCES item_revisions(organization_id, id),
    UNIQUE (product_revision_id, version),
    UNIQUE (organization_id, id, product_revision_id),
    UNIQUE (organization_id, id)
);

CREATE TABLE bom_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    bom_id BIGINT NOT NULL,
    line_no INTEGER NOT NULL CHECK (line_no > 0),
    component_revision_id BIGINT NOT NULL,
    quantity NUMERIC(18,6) NOT NULL CHECK (quantity > 0 AND quantity <> 'NaN'::numeric),
    FOREIGN KEY (organization_id, bom_id) REFERENCES boms(organization_id, id),
    FOREIGN KEY (organization_id, component_revision_id) REFERENCES item_revisions(organization_id, id),
    UNIQUE (bom_id, line_no),
    UNIQUE (organization_id, id, bom_id, component_revision_id),
    UNIQUE (organization_id, id)
);

CREATE TABLE inventory_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    parent_location_id BIGINT,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(255) NOT NULL,
    location_type VARCHAR(30) NOT NULL DEFAULT 'WAREHOUSE' CHECK (location_type IN ('WAREHOUSE', 'BIN', 'PRODUCTION', 'QUARANTINE', 'DAMAGED', 'TRANSIT')),
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (organization_id, parent_location_id) REFERENCES inventory_locations(organization_id, id),
    CHECK (parent_location_id IS NULL OR parent_location_id <> id),
    UNIQUE (organization_id, code),
    UNIQUE (organization_id, id)
);

CREATE TABLE inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    movement_type VARCHAR(40) NOT NULL DEFAULT 'RECEIPT' CHECK (movement_type IN ('RECEIPT', 'TRANSFER', 'PRODUCTION_CONSUMPTION', 'PRODUCTION_OUTPUT', 'SHIPMENT', 'ADJUSTMENT')),
    reference VARCHAR(100),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (organization_id, id)
);

CREATE TABLE inventory_movement_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    movement_id BIGINT NOT NULL,
    item_revision_id BIGINT NOT NULL,
    from_location_id BIGINT,
    to_location_id BIGINT,
    quantity NUMERIC(18,6) NOT NULL CHECK (quantity > 0 AND quantity <> 'NaN'::numeric),
    FOREIGN KEY (organization_id, movement_id) REFERENCES inventory_movements(organization_id, id),
    FOREIGN KEY (organization_id, item_revision_id) REFERENCES item_revisions(organization_id, id),
    FOREIGN KEY (organization_id, from_location_id) REFERENCES inventory_locations(organization_id, id),
    FOREIGN KEY (organization_id, to_location_id) REFERENCES inventory_locations(organization_id, id),
    CHECK (from_location_id IS NOT NULL OR to_location_id IS NOT NULL),
    CHECK (from_location_id IS DISTINCT FROM to_location_id),
    UNIQUE (organization_id, id)
);

CREATE TABLE sales_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    order_number VARCHAR(50) NOT NULL,
    customer_id BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'CONFIRMED', 'RESERVED', 'PARTIALLY_SHIPPED', 'SHIPPED', 'CANCELLED')),
    currency_code CHAR(3) NOT NULL CHECK (currency_code ~ '^[A-Z]{3}$'),
    ordered_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    required_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (organization_id, customer_id) REFERENCES business_partners(organization_id, id),
    UNIQUE (organization_id, order_number),
    UNIQUE (organization_id, id)
);

CREATE TABLE sales_order_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    sales_order_id BIGINT NOT NULL,
    line_no INTEGER NOT NULL CHECK (line_no > 0),
    item_revision_id BIGINT NOT NULL,
    quantity NUMERIC(18,6) NOT NULL CHECK (quantity > 0 AND quantity <> 'NaN'::numeric),
    unit_price NUMERIC(18,4) CHECK (unit_price >= 0 AND unit_price <> 'NaN'::numeric),
    FOREIGN KEY (organization_id, sales_order_id) REFERENCES sales_orders(organization_id, id),
    FOREIGN KEY (organization_id, item_revision_id) REFERENCES item_revisions(organization_id, id),
    UNIQUE (sales_order_id, line_no),
    UNIQUE (organization_id, id, item_revision_id),
    UNIQUE (organization_id, id)
);

CREATE TABLE production_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    production_order_number VARCHAR(50) NOT NULL,
    product_revision_id BIGINT NOT NULL,
    bom_id BIGINT NOT NULL,
    source_sales_order_line_id BIGINT,
    quantity NUMERIC(18,6) NOT NULL CHECK (quantity > 0 AND quantity <> 'NaN'::numeric),
    status VARCHAR(30) NOT NULL DEFAULT 'PLANNED' CHECK (status IN ('PLANNED', 'APPROVED', 'RELEASED', 'IN_PRODUCTION', 'COMPLETED', 'CANCELLED')),
    planned_start_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (organization_id, product_revision_id) REFERENCES item_revisions(organization_id, id),
    FOREIGN KEY (organization_id, bom_id, product_revision_id) REFERENCES boms(organization_id, id, product_revision_id),
    FOREIGN KEY (organization_id, source_sales_order_line_id, product_revision_id) REFERENCES sales_order_lines(organization_id, id, item_revision_id),
    UNIQUE (organization_id, production_order_number),
    UNIQUE (organization_id, id, bom_id),
    UNIQUE (organization_id, id)
);

CREATE TABLE production_order_materials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    production_order_id BIGINT NOT NULL,
    bom_id BIGINT NOT NULL,
    bom_line_id BIGINT NOT NULL,
    component_revision_id BIGINT NOT NULL,
    required_quantity NUMERIC(18,6) NOT NULL CHECK (required_quantity > 0 AND required_quantity <> 'NaN'::numeric),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (organization_id, production_order_id, bom_id) REFERENCES production_orders(organization_id, id, bom_id),
    FOREIGN KEY (organization_id, bom_line_id, bom_id, component_revision_id) REFERENCES bom_lines(organization_id, id, bom_id, component_revision_id),
    UNIQUE (production_order_id, bom_line_id),
    UNIQUE (organization_id, id, component_revision_id),
    UNIQUE (organization_id, id)
);

CREATE TABLE stock_reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    item_revision_id BIGINT NOT NULL,
    location_id BIGINT NOT NULL,
    sales_order_line_id BIGINT,
    production_order_material_id BIGINT,
    quantity NUMERIC(18,6) NOT NULL CHECK (quantity > 0 AND quantity <> 'NaN'::numeric),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'CONSUMED', 'RELEASED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (organization_id, item_revision_id) REFERENCES item_revisions(organization_id, id),
    FOREIGN KEY (organization_id, location_id) REFERENCES inventory_locations(organization_id, id),
    FOREIGN KEY (organization_id, sales_order_line_id, item_revision_id) REFERENCES sales_order_lines(organization_id, id, item_revision_id),
    FOREIGN KEY (organization_id, production_order_material_id, item_revision_id) REFERENCES production_order_materials(organization_id, id, component_revision_id),
    CHECK (num_nonnulls(sales_order_line_id, production_order_material_id) = 1),
    UNIQUE (organization_id, id)
);

