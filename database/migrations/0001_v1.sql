CREATE FUNCTION protect_revision() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF (NEW.organization_id, NEW.item_id, NEW.revision_code) IS DISTINCT FROM (OLD.organization_id, OLD.item_id, OLD.revision_code) THEN
        RAISE EXCEPTION 'Revision identity is immutable; create a new revision';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER preserve_revision_identity BEFORE UPDATE ON item_revisions FOR EACH ROW EXECUTE FUNCTION protect_revision();
