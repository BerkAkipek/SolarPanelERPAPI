CREATE TRIGGER preserve_material_snapshot BEFORE UPDATE OR DELETE ON production_order_materials FOR EACH ROW EXECUTE FUNCTION reject_history_change();

CREATE FUNCTION protect_production_plan() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF (NEW.organization_id, NEW.product_revision_id, NEW.bom_id, NEW.quantity, NEW.source_sales_order_line_id)
       IS DISTINCT FROM (OLD.organization_id, OLD.product_revision_id, OLD.bom_id, OLD.quantity, OLD.source_sales_order_line_id) THEN
        RAISE EXCEPTION 'Production recipe and quantity are immutable; cancel and create another order';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER preserve_production_plan BEFORE UPDATE ON production_orders FOR EACH ROW EXECUTE FUNCTION protect_production_plan();

